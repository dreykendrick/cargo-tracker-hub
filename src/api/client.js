import axios from 'axios';

const API_URL = 'http://localhost:5000/api';

const api = axios.create({
  baseURL: API_URL,
  headers: {
    'Content-Type': 'application/json',
  },
});

api.interceptors.request.use((config) => {
  const token = localStorage.getItem('token');
  if (token) {
    config.headers.Authorization = `Bearer ${token}`;
  }
  return config;
});

api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response?.status === 401) {
      localStorage.removeItem('token');
      localStorage.removeItem('user');
      window.location.href = '/login';
    }
    return Promise.reject(error);
  }
);

export const authAPI = {
  register: (data) => api.post('/auth/register', data),
  login: (data) => api.post('/auth/login', data),
  getMe: () => api.get('/auth/me'),
};

export const productAPI = {
  getAll: (params) => api.get('/products', { params }),
  getById: (id) => api.get(`/products/${id}`),
  create: (data) => api.post('/products', data),
  update: (id, data) => api.put(`/products/${id}`, data),
  delete: (id) => api.delete(`/products/${id}`),
  approve: (id) => api.put(`/products/${id}/approve`),
};

export const orderAPI = {
  create: (data) => api.post('/orders', data),
  processPayment: (data) => api.post('/orders/payment', data),
  getAll: () => api.get('/orders'),
};

export const affiliateAPI = {
  trackClick: (data) => api.post('/affiliate/track', data),
  getStats: () => api.get('/affiliate/stats'),
  generateLink: (productId) => api.get(`/affiliate/link/${productId}`),
};

export default api;
